#!/usr/bin/env python3
"""Generate the embedded trust-roots source of the client (PLAN.md 10, T1).

Reads the byte-exact PEM snapshots of the ISRG roots under scripts/trust-roots/
(published on https://letsencrypt.org/certs/), verifies their DER SHA-256
against the fingerprints pinned below, and writes src/ssh3/s3_ssh3_trust_roots.c
- a plain C17 hex array (no #embed, the canon of the tree).

The verification is a hard gate: a snapshot that does not match the published
fingerprint refuses to generate. Run from the repo root:

    python3 scripts/gen-trust-roots.py
"""

import hashlib
import pathlib
import subprocess
import sys

# The DER SHA-256 fingerprints of the roots, verified against the values
# published for them (the Go fork pins the same pair, cmd/cabundle.go).

EXPECTED = {
    "isrgrootx1.pem": "96bcec06264976f37460779acf28c5a7cfe8a3c0aae11a8ffcee05c0bddf08c6",
    "isrg-root-x2.pem": "69729b8e15a86efc177a57afb7171dfc64add28c2fca8cf1507e34453ccb1470",
}

ROOTS_DIR = pathlib.Path(__file__).resolve().parent / "trust-roots"
OUT_FILE = (
    pathlib.Path(__file__).resolve().parent.parent / "src" / "ssh3" / "s3_ssh3_trust_roots.c"
)

HEADER = """/*
 * Copyright (C) 2026 the ssh3-c authors
 */

/*
 * GENERATED by scripts/gen-trust-roots.py - do not edit by hand.
 *
 * The embedded CA-bundle bootstrap of the client (PLAN.md 10, T1,
 * CERT-VERIFICATION-CANON.md 2.2 the "system CA store" path): the PEM of the
 * ISRG roots, byte-exact snapshots of the certificates published on
 * letsencrypt.org (scripts/trust-roots/).  The DER SHA-256 of each root is
 * verified by the generator:
 *
 *   ISRG Root X1  96:BC:EC:06:26:49:76:F3:74:60:77:9A:CF:28:C5:A7:CF:E8:A3:C0:
 *                 AA:E1:1A:8F:FC:EE:05:C0:BD:DF:08:C6
 *   ISRG Root X2  69:72:9B:8E:15:A8:6E:FC:17:7A:57:AF:B7:17:1D:FC:64:AD:D2:8C:
 *                 2F:CA:8C:F1:50:7E:34:45:3C:CB:14:70
 *
 * The hex array rides instead of #embed (C17, the canon of the tree); the
 * bytes load into the client store through s3_ssh3_aia_trust_bootstrap().
 */

#include <stddef.h>

const unsigned char s3_ssh3_trust_roots_pem[] = {

"""


def der_sha256(pem_path: pathlib.Path) -> str:
    """The SHA-256 of the DER form of the PEM certificate (via openssl)."""
    der = subprocess.run(
        ["openssl", "x509", "-in", str(pem_path), "-outform", "DER"],
        capture_output=True,
        check=True,
    ).stdout
    return hashlib.sha256(der).hexdigest()


def main() -> int:
    blobs = []

    for name, expected in EXPECTED.items():
        path = ROOTS_DIR / name
        pem = path.read_bytes()

        if not pem.endswith(b"\n"):
            print(f"error: {name} does not end with a newline", file=sys.stderr)
            return 1

        got = der_sha256(path)

        if got != expected:
            print(
                f"error: {name} DER SHA-256 mismatch: got {got}, expected {expected}",
                file=sys.stderr,
            )
            return 1

        blobs.append(pem)
        print(f"verified {name}: DER SHA-256 {got}")

    pem = b"".join(blobs)
    lines = []

    for i in range(0, len(pem), 16):
        chunk = pem[i : i + 16]
        lines.append("    " + " ".join(f"0x{b:02x}," for b in chunk))

    body = "\n".join(lines)

    tail = f"""
}};

const size_t s3_ssh3_trust_roots_pem_len = {len(pem)};

/* the empty line keeps the canon of the tree */
"""

    OUT_FILE.write_text(HEADER + body + tail, newline="\n")
    print(f"written {OUT_FILE} ({len(pem)} PEM bytes)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
