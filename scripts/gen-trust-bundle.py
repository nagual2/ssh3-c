#!/usr/bin/env python3
"""Generate the embedded trust-root source from the Mozilla CCADB
report (PLAN.md 14, phase 1b).

Input: the IncludedCACertificateReportPEMCSV export of the CCADB
(https://ccadb.my.salesforce-sites.com/mozilla/IncludedCACertificateReportPEMCSV),
a local snapshot of it - the generator carries no network.

For every row of the report:

  - the Trust Bits carry "Websites" (the dial context of the client)
  - the TLS distrust date is empty (a root leaving the TLS trust
    never anchors, whatever the date is)
  - the DER SHA-256 of the PEM row matches the fingerprint column of
    the same row - the hard gate, a mismatched row refuses the
    whole generation
  - the fingerprints dedupe (a repeated root rides once)

The ISRG Root X1/X2 pins of the previous generation stay as the
mandatory members (the pair the wave-13 trust tests pin).

Output: src/ssh3/s3_ssh3_trust_roots.c - the same
s3_ssh3_trust_roots_pem symbol the bootstrap pours, now the
browser-size set (the hex array, C17, no #embed - the canon of the
tree).

Run from the repo root:

    python3 scripts/gen-trust-bundle.py scripts/trust-roots/ccadb-<date>.csv
"""

import csv
import hashlib
import pathlib
import subprocess
import sys

SOURCE_URL = "https://ccadb.my.salesforce-sites.com/mozilla/IncludedCACertificateReportPEMCSV"

# the mandatory members (the go-fork pins, the wave-13 tests)

MANDATORY = {
    "96bcec06264976f37460779acf28c5a7cfe8a3c0aae11a8ffcee05c0bddf08c6": "ISRG Root X1",
    "69729b8e15a86efc177a57afb7171dfc64add28c2fca8cf1507e34453ccb1470": "ISRG Root X2",
}

OUT_FILE = (
    pathlib.Path(__file__).resolve().parent.parent / "src" / "ssh3" / "s3_ssh3_trust_roots.c"
)


def der_sha256(pem_text: str) -> str:
    """The SHA-256 of the DER form of the PEM certificate (via openssl)."""
    proc = subprocess.run(
        ["openssl", "x509", "-outform", "DER"],
        input=pem_text.encode(),
        capture_output=True,
        check=True,
    )
    return hashlib.sha256(proc.stdout).hexdigest()


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: gen-trust-bundle.py <ccadb-report.csv>", file=sys.stderr)
        return 1

    report = pathlib.Path(sys.argv[1])

    if not report.is_file():
        print(f"error: the report {report} is missing", file=sys.stderr)
        return 1

    csv_sha = hashlib.sha256(report.read_bytes()).hexdigest()

    with report.open(newline="", errors="replace") as f:
        rows = list(csv.DictReader(f))

    picked = {}
    dropped_distrust = 0
    dropped_no_websites = 0

    for row in rows:

        if "Websites" not in row.get("Trust Bits", ""):
            dropped_no_websites += 1
            continue

        if row.get("Distrust for TLS After Date", "").strip():
            dropped_distrust += 1
            continue

        pem = row.get("PEM Info", "").strip().strip("'")

        if not pem.startswith("-----BEGIN CERTIFICATE-----"):
            print(
                "error: a row without the PEM block rides past:",
                row.get("Common Name or Certificate Name", "?"),
                file=sys.stderr,
            )
            return 1

        got = der_sha256(pem)
        claimed = row.get("SHA-256 Fingerprint", "").strip().lower().replace(":", "")

        if got != claimed:
            cn = row.get("Common Name or Certificate Name", "?")
            print(
                f"error: {cn}: the DER SHA-256 mismatch: got {got}, the report claims {claimed}",
                file=sys.stderr,
            )
            return 1

        picked[got] = pem

    missing = [name for fp, name in MANDATORY.items() if fp not in picked]

    if missing:
        print(f"error: the mandatory members left the set: {missing}", file=sys.stderr)
        return 1

    pems = []
    for fp in sorted(picked):
        pems.append(picked[fp].rstrip() + "\n")

    blob = "".join(pems).encode()
    isrg_note = ", ".join(f"{name} ({fp[:12]}...)" for fp, name in sorted(MANDATORY.items(), key=lambda kv: kv[1]))

    header = f"""/*
 * Copyright (C) 2026 the ssh3-c authors
 */

/*
 * GENERATED by scripts/gen-trust-bundle.py - do not edit by hand.
 *
 * The embedded trust set of the client (PLAN.md 14, phase 1b): the
 * browser-size set of the root certificates - the Websites trust
 * bit of the Mozilla CCADB report, the TLS-distrusted rows ride
 * out, the DER SHA-256 of every row verified against the report at
 * the generation time.
 *
 * Source: {SOURCE_URL}
 * Report snapshot: scripts/trust-roots/ (the SHA-256 of the csv:
 * {csv_sha})
 * Roots embedded: {len(picked)} (of {len(rows)} report rows, {dropped_no_websites} without the
 * Websites bit, {dropped_distrust} TLS-distrusted)
 * Mandatory members verified: {isrg_note}
 *
 * The hex array rides instead of #embed (C17, the canon of the
 * tree); the bytes load into the client store through
 * s3_ssh3_aia_trust_bootstrap().
 */

#include <stddef.h>

const unsigned char s3_ssh3_trust_roots_pem[] = {{
"""

    body = []
    for i in range(0, len(blob), 16):
        chunk = blob[i : i + 16]
        body.append("    " + " ".join(f"0x{b:02x}," for b in chunk))

    tail = f"""
}};

const size_t s3_ssh3_trust_roots_pem_len = {len(blob)};

/* the empty line keeps the canon of the tree */
"""

    OUT_FILE.write_text(header + "\n".join(body) + tail, newline="\n")

    print(f"verified {len(picked)} roots, embedded {len(blob)} PEM bytes")
    print(f"written {OUT_FILE}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
